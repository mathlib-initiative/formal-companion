"""Build a run's tend root: config.yaml, .tend/*.yaml, bin/ wrappers, gate/.

Ported from the v1 campaign's five orchestration roots
(``tao-diff-tend`` and its four siblings): their ``config.yaml`` files differed
only in the entrypoint, the two ``bin/*.sh`` paths and the two concurrency
numbers, and their four ``.tend/*.yaml`` files were byte-identical. Everything
else here is the correction the design critique required:

* ``validation_commands`` and ``pre_merge_validation_commands`` call the gate by
  **absolute path outside the worktree** (``<gate_dir>/verify_findings.py``)
  instead of ``python3 scripts/verify_findings.py`` from inside the tree the
  worker commits to, and they pass ``--changed-files`` so a contribution that
  touched anything but its own findings and task file is refused;
* ``bin/worker-agent.sh`` / ``bin/reviewer-agent.sh`` are generated wrappers that
  set the ``CF_*`` environment and exec one of the skill's bridges
  (``scripts/run/bridge-*.sh``), so the bridge stays one file for five presets.

Paths written into ``config.yaml`` are the **run host's** paths: for a remote
host they are ``<remote_root>/<run-id>-tend`` etc., which is where
``scripts/run/manifest.py`` rsyncs this directory.
"""

from __future__ import annotations

import pathlib
import shutil
import stat
from dataclasses import dataclass
from typing import Any

from cflib.paths import skill_root, templates_dir

from . import models
from .presets import Preset
from .render import render_file

BRIDGE_SCRIPTS = {
    "agentbox-claude": ("bridge-agentbox.sh", "claude"),
    "agentbox-codex": ("bridge-agentbox.sh", "codex"),
    "claude-p": ("bridge-claude-p.sh", ""),
    "tend-agent": ("bridge-tend-agent.sh", ""),
}

WRAPPER = """#!/usr/bin/env bash
# Generated by {generator} for run {run_id} (preset {preset}) — role {role}.
# Regenerate rather than edit: run.yaml records the sha of what was launched.
set -uo pipefail
ROOT="$(cd -- "$(dirname -- "${{BASH_SOURCE[0]}}")/.." && pwd)"
export CF_ROLE={role}
export CF_BRIDGE_ROOT="$ROOT"
export CF_PROMPT_DIR="{prompts_dir}"
{env_lines}export CF_GATE_CMD="{gate_command}"
exec "$ROOT/bin/{bridge}" {role} "$@"
"""


@dataclass
class TendRootPlan:
    """Where a run's tend root lives locally and on the run host."""

    local: pathlib.Path          # <workspace>/runs/<id>/tend-root
    tend_root: str               # host path of that same directory
    entrypoint: str              # host path of the entrypoint repo
    gate_dir: str                # host path of the out-of-tree gate
    prompts_dir: str             # host path of the rendered prompts
    merge_target_branch: str = "main"
    #: the out-of-tree gate this root's validation commands run: the findings
    #: gate, or the locate gate for a locate run (scripts/locate/tend_root.py)
    gate_script: str = "verify_findings.py"

    @property
    def gate_command(self) -> str:
        return (f"python3 {self.gate_dir}/{self.gate_script} "
                f"--gate-config {self.gate_dir}/gate.json")


def _write_exec(path: pathlib.Path, text: str) -> pathlib.Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return path


def make_tend_root(
    plan: TendRootPlan,
    preset: Preset,
    *,
    run_id: str,
    gate_config: dict,
    prompts: dict[str, str] | None = None,
    agent: dict[str, Any] | None = None,
    task_count: int = 0,
    model: str | None = None,
    allow_sandbox_bypass: bool = False,
    tdir: pathlib.Path | None = None,
    gate_src: pathlib.Path | None = None,
    bridges_src: pathlib.Path | None = None,
    decl_index_src: pathlib.Path | None = None,
    config_template: str = "config.yaml.tmpl",
    readme_template: str = "README.md.tmpl",
    gate_files: tuple[str, ...] = ("verify_findings.py", "check_changed_files.py"),
    extra_env: dict[str, dict[str, str]] | None = None,
    context: dict[str, Any] | None = None,
    generator: str = "cf plan-run",
) -> dict[str, Any]:
    """Write the tend root. Returns {"files": [...], "warnings": [...]}

    ``model`` is the run's RESOLVED worker model (``cf plan-run --model`` wins,
    then the workspace, then the preset -- see ``plan.models.resolve``).  It
    reaches the agents two ways, because the two backends read different things:
    the generated ``.tend/worker-agent.yaml`` for the tend-agent backend, and
    ``CF_MODEL`` in the wrapper for the agentbox and claude-p bridges.  Recording
    a model in run.yaml that the bridge never received is worse than recording
    none: a regression comparison would compare two tiers claiming one id.

    ``allow_sandbox_bypass`` (``cf plan-run --allow-sandbox-bypass``) is the ONLY
    thing that stages ``CF_ALLOW_SANDBOX_BYPASS=1`` into the wrappers, which is
    what ``bridge-agentbox.sh`` reads to run with approvals and the sandbox OFF.
    Default off.  Without it the opt-in existed only as a variable an operator
    could export by hand on the host, so ``run.yaml``'s record of what the agents
    may do could not be made true by anything this tool does.

    The ``model:`` block in the generated ``.tend/*-agent.yaml`` belongs to the
    tend-agent backend alone -- ``config.yaml`` sends every other bridge through
    ``bin/<role>-agent.sh``, which carries ``CF_MODEL`` -- so its Anthropic
    ``provider``/``api`` pair is that backend's, and a codex preset's yaml names
    the run's model under it deliberately: two files in one root disagreeing
    about which tier ran is the defect this argument exists to close.  Nothing
    reads that block unless the preset's ``bridge`` is ``tend-agent``.

    A locate run (``scripts/locate/tend_root.py``) renders the same root with its
    own ``config_template`` and ``readme_template``, its own ``gate_files`` and
    ``extra_env`` -- ``{role: {VAR: value}}`` exported by that role's wrapper
    only, so a worker-only allowlist entry never reaches the reviewer -- and
    ``context`` adds the slots its templates read.
    """
    import json

    tdir = pathlib.Path(tdir or (templates_dir() / "tend"))
    gate_src = pathlib.Path(gate_src or (skill_root() / "scripts" / "gate"))
    bridges_src = pathlib.Path(bridges_src or (skill_root() / "scripts" / "run"))
    model = model or preset.model
    agent = {
        "agent_provider": "anthropic",
        "agent_api": "anthropic_messages",
        "agent_model": model or models.DEFAULTS["tend_worker"],
        "reviewer_agent_model": model or models.DEFAULTS["tend_reviewer"],
        "worker_effort": "low",
        "reviewer_effort": "low",
        "max_output_tokens": 32768,
        "max_wall_time_seconds": 7200.0,
        "model_timeout_seconds": 600.0,
        **(agent or {}),
    }
    root = plan.local
    root.mkdir(parents=True, exist_ok=True)
    files: list[pathlib.Path] = []
    warnings: list[str] = []

    ctx = {
        "run_id": run_id,
        "preset": preset.name,
        "entrypoint": plan.entrypoint,
        "tend_root": plan.tend_root,
        "gate_dir": plan.gate_dir,
        "merge_target_branch": plan.merge_target_branch,
        "max_workers": preset.max_workers,
        "max_reviewers": preset.max_reviewers,
        "bridge": preset.bridge,
        "model": model or "(bridge default)",
        "book_access": preset.book_access,
        "sources_inline": ", ".join(sorted(gate_config.get("sources") or {})) or "(none)",
        "task_count": task_count,
        "gate_script": plan.gate_script,
        **agent,
        **(context or {}),
    }
    (root / "config.yaml").write_text(render_file(tdir / config_template, ctx), encoding="utf-8")
    files.append(root / "config.yaml")
    (root / "README.md").write_text(render_file(tdir / readme_template, ctx), encoding="utf-8")
    files.append(root / "README.md")

    dot = root / ".tend"
    dot.mkdir(exist_ok=True)
    for name, tmpl in (
        ("worker-agent.yaml", "worker-agent.yaml.tmpl"),
        ("reviewer-agent.yaml", "reviewer-agent.yaml.tmpl"),
        ("worker-cfg.yaml", "cfg.yaml.tmpl"),
        ("reviewer-cfg.yaml", "cfg.yaml.tmpl"),
    ):
        (dot / name).write_text(render_file(tdir / tmpl, ctx), encoding="utf-8")
        files.append(dot / name)

    # prompts: kept inside the tend root so `.tend/*.yaml`'s ../prompts resolves
    # and so a local run needs no rsync step.
    if prompts:
        pdir = root / "prompts"
        pdir.mkdir(exist_ok=True)
        for name, text in prompts.items():
            (pdir / name).write_text(text, encoding="utf-8")
            files.append(pdir / name)

    # bin/: generated wrappers + the skill's bridges
    bridge_file, host = BRIDGE_SCRIPTS.get(preset.bridge, ("", ""))
    bindir = root / "bin"
    bindir.mkdir(exist_ok=True)
    if bridge_file:
        env_lines = ""
        if host:
            env_lines += f"export CF_AGENT_HOST={host}\n"
        if agent.get("agentbox_profile"):
            env_lines += f"export CF_AGENTBOX_PROFILE={agent['agentbox_profile']}\n"
        # Every bridge passes its model flag only when CF_MODEL is set, so this
        # is the line that makes `--model` reach the agent instead of only
        # reaching run.yaml.
        if model:
            env_lines += f"export CF_MODEL={model}\n"
        if allow_sandbox_bypass:
            # Deliberate, recorded in run.yaml and visible in the wrapper the
            # operator can read: the bridge otherwise denies by default.
            env_lines += "export CF_ALLOW_SANDBOX_BYPASS=1\n"
        for role in ("worker", "reviewer"):
            role_lines = "".join(f"export {name}=\"{value}\"\n" for name, value
                                 in sorted((extra_env or {}).get(role, {}).items()))
            files.append(
                _write_exec(
                    bindir / f"{role}-agent.sh",
                    WRAPPER.format(
                        generator=generator,
                        run_id=run_id,
                        preset=preset.name,
                        role=role,
                        prompts_dir=plan.prompts_dir,
                        env_lines=env_lines + role_lines,
                        gate_command=plan.gate_command,
                        bridge=bridge_file,
                    ),
                )
            )
        src = bridges_src / bridge_file
        if src.exists():
            shutil.copy2(src, bindir / bridge_file)
            (bindir / bridge_file).chmod(0o755)
            files.append(bindir / bridge_file)
            for helper in ("normalize_result.py", "extract_final_json.py"):
                if (bridges_src / helper).exists():
                    shutil.copy2(bridges_src / helper, bindir / helper)
                    files.append(bindir / helper)
        else:
            warnings.append(
                f"bridge {src} is missing; cf run rsyncs scripts/run/bridge-*.sh into "
                f"{plan.tend_root}/bin/, so the wrapper will find it on the host"
            )
    else:
        warnings.append(f"preset {preset.name} has bridge {preset.bridge!r}: no agent wrapper written")

    # gate/: a local copy so a local run has the gate out of the worktree too.
    gdir = root / "gate"
    gdir.mkdir(exist_ok=True)
    for name in gate_files:
        if (gate_src / name).exists():
            shutil.copy2(gate_src / name, gdir / name)
            files.append(gdir / name)
        else:
            warnings.append(f"gate file missing: {gate_src / name}")
    (gdir / "gate.json").write_text(json.dumps(gate_config, indent=2) + "\n", encoding="utf-8")
    files.append(gdir / "gate.json")
    # The declaration index travels WITH the gate: gate.json names it by the
    # host path <gate_dir>/decl-index.json, and `cf run` rsyncs this directory.
    if decl_index_src and pathlib.Path(decl_index_src).exists():
        shutil.copy2(decl_index_src, gdir / "decl-index.json")
        files.append(gdir / "decl-index.json")
    elif gate_config.get("decl_index"):
        warnings.append(
            f"gate.json names decl_index {gate_config['decl_index']} but no index was staged "
            "in the gate directory; the phantom-name check will fail closed on the host")

    return {"files": [str(p) for p in files], "warnings": warnings}
